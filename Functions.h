#ifndef Functions_h
#define Functions_h

#include <stdio.h>
#include <stdlib.h>
#include <math.h>
#include <stdbool.h>
#include <time.h>

/**
 * @brief Обчислює значення математичної функції f(x).
 *
 * @details Обчислює значення поліноміальної функції
 * f(x) = -0.5 * (x - 64)^3 - 3 * x^2 + 10
 * для заданої точки x.
 *
 * @param x Значення вхідної змінної.
 *
 * @return Обчислене значення f(x).
 */
double f(double x);

/**
 * @brief Обчислює значення першої похідної f'(x).
 *
 * @details Обчислює значення першої похідної
 * f'(x) = -1.5 * (x - 64)^2 - 6 * x,
 * яка використовується для перевірки монотонності функції.
 *
 * @param x Значення вхідної змінної.
 *
 * @return Обчислене значення f'(x).
 */
double df(double x);

/**
 * @brief Обчислює значення другої похідної f''(x).
 *
 * @details Обчислює значення другої похідної
 * f''(x) = -3 * (x - 64) - 6,
 * яка використовується для вибору нерухомої точки
 * методу хорд.
 *
 * @param x Значення вхідної змінної.
 *
 * @return Обчислене значення f''(x).
 */
double d2f(double x);

/**
 * @brief Безпечно зчитує число з плаваючою крапкою.
 *
 * @details Зчитує значення типу double та повторює введення
 * у разі помилки.
 *
 * @param prompt Текст підказки для користувача.
 *
 * @return Зчитане значення типу double.
 */
double readDouble(const char *prompt);

/**
 * @brief Безпечно зчитує додатне ціле число.
 *
 * @details Вимагає введення цілого числа, що строго більше нуля.
 *
 * @param prompt Текст підказки для користувача.
 *
 * @return Зчитане додатне ціле число.
 */
int readPositiveInt(const char *prompt);

/**
 * @brief Перевіряє ізоляцію кореня на інтервалі [a, b].
 *
 * @details Перевіряє умову f(a) * f(b) <= 0,
 * а також знак першої похідної на межах інтервалу
 * для перевірки монотонності функції та єдиності кореня.
 *
 * @param a Ліва межа інтервалу.
 * @param b Права межа інтервалу.
 *
 * @return true, якщо умова зміни знака виконується,
 * інакше false.
 */
bool verifyInterval(double a, double b);

/**
 * @brief Розв'язує нелінійне рівняння методом хорд.
 *
 * @details Використовує нерухому точку, яка вибирається
 * за умовою f(x) * f''(x) > 0.
 * Обчислення виконуються до досягнення заданої точності
 * або перевищення максимальної кількості ітерацій.
 *
 * @param a Ліва межа інтервалу.
 * @param b Права межа інтервалу.
 * @param eps Необхідна точність обчислень.
 * @param maxIter Максимально дозволена кількість ітерацій.
 * @param debug Прапорець покрокового виведення результатів.
 */
void chordMethod(double a, double b, double eps, int maxIter, bool debug);

/**
 * @brief Розв'язує нелінійне рівняння методом бісекції.
 *
 * @details Ділить інтервал [a, b] навпіл та вибирає підінтервал,
 * на якому зберігається зміна знака функції.
 * Обчислення виконуються до досягнення умови
 * (b - a) / 2 <= eps або перевищення максимальної
 * кількості ітерацій.
 *
 * @param a Ліва межа інтервалу.
 * @param b Права межа інтервалу.
 * @param eps Необхідна точність обчислень.
 * @param maxIter Максимально дозволена кількість ітерацій.
 * @param debug Прапорець покрокового виведення результатів.
 */
void bisectionMethod(double a, double b, double eps, int maxIter, bool debug);

#endif